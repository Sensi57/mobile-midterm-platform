    extraSmall = RoundedCornerShape(8.dp),
    small = RoundedCornerShape(12.dp),
    medium = RoundedCornerShape(18.dp),
    large = RoundedCornerShape(24.dp),
    extraLarge = RoundedCornerShape(32.dp)
)

@Composable
fun StudyFlowTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit
) {
    MaterialTheme(
        colorScheme = if (darkTheme) DarkColors else LightColors,
        typography = AppTypography,
        shapes = AppShapes,
        content = content
    )
}

@Composable
fun Priority.accentColor(): Color {
    val dark = isSystemInDarkTheme()
    return when (this) {
        Priority.LOW -> if (dark) PriorityLowDark else PriorityLowLight
        Priority.MEDIUM -> if (dark) PriorityMediumDark else PriorityMediumLight
        Priority.HIGH -> if (dark) PriorityHighDark else PriorityHighLight
    }
}
